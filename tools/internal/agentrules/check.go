package agentrules

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	// RulesDir holds the one copy of every area rule, where Claude Code
	// discovers path-scoped rules.
	RulesDir = ".claude/rules"
	// GuidePath is the root agent guide; AGENTS.md is a symlink to it.
	GuidePath = ".claude/CLAUDE.md"
	// MaxGuideBytes keeps the root guide well under Codex's default 32 KiB
	// project_doc_max_bytes, which may also be shared with a global
	// ~/.codex/AGENTS.md.
	MaxGuideBytes = 16 * 1024

	IndexStart = "<!-- agent-rules-index:start (generated by `make agent-rules-index`; do not edit by hand) -->"
	IndexEnd   = "<!-- agent-rules-index:end -->"
)

// strayEntries reports anything in RulesDir other than top-level .md files.
// Claude Code also loads rules from subdirectories, so a nested file would
// load without being checked or indexed. Dotfiles such as .DS_Store are ignored.
func strayEntries(root string) []error {
	entries, err := os.ReadDir(filepath.Join(root, RulesDir))
	if err != nil {
		return nil
	}
	var errs []error
	for _, e := range entries {
		if strings.HasPrefix(e.Name(), ".") || (!e.IsDir() && strings.HasSuffix(e.Name(), ".md")) {
			continue
		}
		errs = append(errs, fmt.Errorf("%s/%s: only top-level .md rule files belong in %s", RulesDir, e.Name(), RulesDir))
	}
	return errs
}

// LoadRules parses every rule file in RulesDir, sorted by name.
//
// Rules must be regular files. Claude Code treats a symlink whose target lies
// outside the session's working directory as an external import and never
// loads it path-scoped, so a symlink into docs/ stops working for anyone who
// starts a session in a subdirectory such as operator/.
func LoadRules(root string) ([]Rule, error) {
	files, err := filepath.Glob(filepath.Join(root, RulesDir, "*.md"))
	if err != nil {
		return nil, fmt.Errorf("listing %s: %w", RulesDir, err)
	}
	sort.Strings(files)
	var rules []Rule
	var errs []error
	errs = append(errs, strayEntries(root)...)
	for _, f := range files {
		rel := RulesDir + "/" + filepath.Base(f)
		info, err := os.Lstat(f)
		if err != nil {
			errs = append(errs, fmt.Errorf("inspecting %s: %w", rel, err))
			continue
		}
		if !info.Mode().IsRegular() {
			errs = append(errs, fmt.Errorf("%s must be a regular file, not a symlink: Claude Code skips path-scoped rules linked from outside the session's working directory", rel))
			continue
		}
		content, err := os.ReadFile(f)
		if err != nil {
			errs = append(errs, fmt.Errorf("reading %s: %w", rel, err))
			continue
		}
		r, err := ParseRule(strings.TrimSuffix(filepath.Base(f), ".md"), content)
		if err != nil {
			errs = append(errs, fmt.Errorf("%s: %w", rel, err))
			continue
		}
		rules = append(rules, r)
	}
	if len(rules) == 0 && len(errs) == 0 {
		errs = append(errs, fmt.Errorf("no rule files found in %s", RulesDir))
	}
	return rules, errors.Join(errs...)
}

// RenderIndex renders the index block for the root guide, markers included.
func RenderIndex(rules []Rule) string {
	var b strings.Builder
	b.WriteString(IndexStart + "\n")
	b.WriteString("| If you touch | Read first | Because |\n")
	b.WriteString("| --- | --- | --- |\n")
	for _, r := range rules {
		paths := make([]string, len(r.Paths))
		for i, p := range r.Paths {
			paths[i] = "`" + p + "`"
		}
		fmt.Fprintf(&b, "| %s | `%s/%s.md` | %s |\n", strings.Join(paths, ", "), RulesDir, r.Name, r.Summary)
	}
	b.WriteString(IndexEnd)
	return b.String()
}

// indexBounds returns the byte offsets of the index block, end exclusive.
func indexBounds(guide string) (int, int, error) {
	start := strings.Index(guide, IndexStart)
	end := strings.Index(guide, IndexEnd)
	if start < 0 || end < start {
		return 0, 0, fmt.Errorf("%s has no index markers; add the lines %q and %q where the index belongs", GuidePath, IndexStart, IndexEnd)
	}
	return start, end + len(IndexEnd), nil
}

// WriteIndex regenerates the index block in the root guide.
func WriteIndex(root string) error {
	rules, err := LoadRules(root)
	if err != nil {
		return err
	}
	path := filepath.Join(root, GuidePath)
	content, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("reading %s: %w", GuidePath, err)
	}
	guide := string(content)
	start, end, err := indexBounds(guide)
	if err != nil {
		return err
	}
	updated := guide[:start] + RenderIndex(rules) + guide[end:]
	if err := os.WriteFile(path, []byte(updated), 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", GuidePath, err)
	}
	return nil
}

// Check reports every way the rule files and the root guide disagree.
func Check(root string) []error {
	var errs []error
	rules, err := LoadRules(root)
	if err != nil {
		errs = append(errs, err)
	}

	content, err := os.ReadFile(filepath.Join(root, GuidePath))
	if err != nil {
		return append(errs, fmt.Errorf("reading %s: %w", GuidePath, err))
	}
	if len(content) > MaxGuideBytes {
		errs = append(errs, fmt.Errorf("%s is %d bytes, over the %d-byte limit; move area-specific guidance into %s", GuidePath, len(content), MaxGuideBytes, RulesDir))
	}
	guide := string(content)
	start, end, err := indexBounds(guide)
	if err != nil {
		return append(errs, err)
	}
	if rules != nil && guide[start:end] != RenderIndex(rules) {
		errs = append(errs, fmt.Errorf("the index in %s is stale; run make agent-rules-index", GuidePath))
	}
	return errs
}
