// These tests use Ginkgo (BDD-style Go testing framework). Refer to
// http://onsi.github.io/ginkgo/ to learn more about Ginkgo.

var cfg *rest.Config
var k8sClient client.Client
var cachedClient client.Client
var testEnv *envtest.Environment
var ctx context.Context
var cancel context.CancelFunc

func TestAPIs(t *testing.T) {
	RegisterFailHandler(Fail)

	RunSpecs(t, "Webhook Suite")
}

var _ = BeforeSuite(func() {
	logf.SetLogger(zap.New(zap.WriteTo(GinkgoWriter), zap.UseDevMode(true)))

	ctx, cancel = context.WithCancel(context.TODO())

	By("bootstrapping test environment")
	testEnv = &envtest.Environment{
		// Install only the nodewright.nvidia.com group's CRDs. The webhook config
		// under config/webhook also targets the legacy skyhook.nvidia.com group, but
		// envtest only registers the webhooks whose CRDs are installed, so the legacy
		// entries are inert here.
		CRDDirectoryPaths: []string{
			filepath.Join("..", "..", "..", "config", "crd", "bases", "nodewright.nvidia.com_nodewrights.yaml"),
			filepath.Join("..", "..", "..", "config", "crd", "bases", "nodewright.nvidia.com_deploymentpolicies.yaml"),
		},
		ErrorIfCRDPathMissing: false,

		// The BinaryAssetsDirectory is only required if you want to run the tests directly
		// without call the makefile target test. If not informed it will look for the
		// default path defined in controller-runtime which is /usr/local/kubebuilder/.
		// Note that you must have the required binaries setup under the bin directory to perform
		// the tests directly. When we run make test it will be setup and used automatically.
		BinaryAssetsDirectory: filepath.Join("..", "..", "..", "bin", "k8s",
			fmt.Sprintf("1.36.0-%s-%s", runtime.GOOS, runtime.GOARCH)),

		WebhookInstallOptions: envtest.WebhookInstallOptions{
			Paths: []string{filepath.Join("..", "..", "..", "config", "webhook")},
		},
	}

	var err error
	// cfg is defined in this file globally.
	cfg, err = testEnv.Start()
	Expect(err).NotTo(HaveOccurred())
	Expect(cfg).NotTo(BeNil())

	scheme := apimachineryruntime.NewScheme()
	err = AddToScheme(scheme)
	Expect(err).NotTo(HaveOccurred())

	err = admissionv1.AddToScheme(scheme)
	Expect(err).NotTo(HaveOccurred())
	err = admissionregistrationv1.AddToScheme(scheme)
	Expect(err).NotTo(HaveOccurred())

	//+kubebuilder:scaffold:scheme

	k8sClient, err = client.New(cfg, client.Options{Scheme: scheme})
	Expect(err).NotTo(HaveOccurred())
	Expect(k8sClient).NotTo(BeNil())

	// start webhook server using Manager
	webhookInstallOptions := &testEnv.WebhookInstallOptions
	mgr, err := ctrl.NewManager(cfg, ctrl.Options{
		Scheme: scheme,
		WebhookServer: webhook.NewServer(webhook.Options{
			Host:    webhookInstallOptions.LocalServingHost,
			Port:    webhookInstallOptions.LocalServingPort,
			CertDir: webhookInstallOptions.LocalServingCertDir,
		}),
		LeaderElection: false,
		Metrics:        metricsserver.Options{BindAddress: "0"},
	})
	Expect(err).NotTo(HaveOccurred())

	cachedClient = mgr.GetClient()

	err = (&NodeWright{}).SetupWebhookWithManager(mgr)
	Expect(err).NotTo(HaveOccurred())

	err = (&DeploymentPolicy{}).SetupWebhookWithManager(mgr)
	Expect(err).NotTo(HaveOccurred())

	//+kubebuilder:scaffold:webhook

	go func() {
		defer GinkgoRecover()
		err = mgr.Start(ctx)
		Expect(err).NotTo(HaveOccurred())
	}()

	// wait for the webhook server to get ready
	dialer := &net.Dialer{Timeout: time.Second}
	addrPort := fmt.Sprintf("%s:%d", webhookInstallOptions.LocalServingHost, webhookInstallOptions.LocalServingPort)
	Eventually(func() error {
		conn, err := tls.DialWithDialer(dialer, "tcp", addrPort, &tls.Config{InsecureSkipVerify: true})
		if err != nil {
			return err
		}
		return conn.Close()
	}).Should(Succeed())

})

var _ = AfterSuite(func() {
	cancel()
	By("tearing down the test environment")
	err := testEnv.Stop()
	Expect(err).NotTo(HaveOccurred())
})

// waitForPolicyInWebhookCache blocks until the manager's cache has observed the named
// DeploymentPolicy. The NodeWright validating webhook reads through that cache, while
// k8sClient reads straight from the apiserver, so a NodeWright created immediately
// after its policy races the informer and is denied with "deploymentPolicy ... not
// found". Waiting on the same client the webhook uses closes that window.
func waitForPolicyInWebhookCache(name string) {
	GinkgoHelper()
	Eventually(func() error {
		return cachedClient.Get(ctx, types.NamespacedName{Name: name}, &DeploymentPolicy{})
	}, "10s", "100ms").Should(Succeed())
}

// waitForNodeWrightGoneFromWebhookCache blocks until the manager's cache has observed that
// the named NodeWright is deleted. Same race as waitForPolicyInWebhookCache, in the removal
// direction: the DeploymentPolicy validating webhook lists NodeWrights through the cache, so
// confirming the delete against the apiserver with k8sClient is not enough. The informer can
// still return the object, and the policy delete is denied with "still referenced by 1
// NodeWright(s)".
func waitForNodeWrightGoneFromWebhookCache(name string) {
	GinkgoHelper()
	Eventually(func() bool {
		return apierrors.IsNotFound(cachedClient.Get(ctx, types.NamespacedName{Name: name}, &NodeWright{}))
	}, "10s", "100ms").Should(BeTrue())
}
